import streamlit as st
from agents.incident_agent import analyze_incident
from agents.risk_agent import assess_risk
from agents.resource_agent import recommend_resources
from agents.route_agent import suggest_route
from agents.coordinator import build_plan
from agents.replanner import replan
from utils.llm import generate_explanation

st.set_page_config(page_title="ResQMind AI", page_icon="🚨", layout="wide")
st.title("🚨 ResQMind AI")
st.caption("NEXAI • Autonomous Emergency Response Intelligence • Understand. Coordinate. Replan.")

with st.sidebar:
    st.header("Incident Simulator")
    scenario = st.selectbox("Scenario", ["Multi-Vehicle Highway Accident", "Building Fire", "Flooded Road Emergency"])
    update = st.checkbox("Simulate new incident update")
    st.divider()
    st.info("Hackathon prototype using simulated data. Authorized humans remain in control of real-world actions.")

scenarios = {
    "Multi-Vehicle Highway Accident": {"type":"Road accident","location":"Simulated Highway Sector 12","injured":7,"smoke":True,"blocked":True,"visibility":"Reduced","hospital_capacity":"Available"},
    "Building Fire": {"type":"Building fire","location":"Simulated Industrial Block B","injured":4,"smoke":True,"blocked":False,"visibility":"Low","hospital_capacity":"Available"},
    "Flooded Road Emergency": {"type":"Flooded road","location":"Simulated Riverside Road","injured":2,"smoke":False,"blocked":True,"visibility":"Reduced","hospital_capacity":"Available"}
}

incident = analyze_incident(scenarios[scenario])
risk = assess_risk(incident)
resources = recommend_resources(incident, risk)
route = suggest_route(incident)
plan = build_plan(incident, risk, resources, route)
if update:
    plan = replan(plan, {"new_hazard":"Fire risk increased"})

st.subheader("Live Incident Overview")
c1,c2,c3,c4 = st.columns(4)
c1.metric("Incident", incident["event_type"])
c2.metric("Risk", risk["level"])
c3.metric("Estimated Injured", incident["injured"])
c4.metric("Route", route["recommendation"])
st.divider()

left,right = st.columns(2)
with left:
    st.subheader("🧠 Agent Reasoning")
    for name, output in [("Incident Agent",incident),("Risk Agent",risk),("Resource Agent",resources),("Route Agent",route)]:
        with st.expander(name, expanded=True): st.json(output)
with right:
    st.subheader("🎯 Coordinated Response Plan")
    st.success("Plan generated by Coordination Agent")
    for i,action in enumerate(plan["actions"],1): st.write(f"**{i}.** {action}")
    st.write("**Priority:**",plan["priority"])
    st.write("**Rationale:**",plan["rationale"])

st.divider(); st.subheader("🔄 What-If Simulator")
a,b,c = st.columns(3)
a.metric("Scenario A","14 min","Normal route")
b.metric("Scenario B","11 min","Alternate route")
c.metric("Scenario C","9 min","Extra ambulance + alternate route")
st.caption("Illustrative simulation outputs for the hackathon prototype.")
if st.button("✨ Generate AI Explanation"):
    st.info(generate_explanation(plan))
st.caption("NEXAI • ResQMind AI | AI recommends and coordinates. Authorized humans remain in control.")
